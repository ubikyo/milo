// What the server pushes to a person when an item they follow
// changes. Distinct from the version counters (events.ts): those tell
// all clients "reread the projects", this one is addressed to a person
// and tells them a fact.

import type { Id } from "./domain.js";
import type { VersionPayload } from "./events.js";

/**
 * The item in question, or the family of what was deleted: "card"
 * covers the whole Tasks mode — a deleted list or board is filed
 * under it. "support": a request from the Support mode. "access": an item
 * of the Access mode — a monitored machine that changes state — ; the id
 * is that of its category, which is what opens.
 */
export type NotificationKind = "project" | "card" | "support" | "access";

export interface Notification {
  /** Randomly generated by the server: serves as the display key. */
  id: string;
  kind: NotificationKind;
  target_id: Id;
  /** The name of the item, as it appears in the application. */
  title: string;
  /** What changed, in one sentence — "a modifié la fiche", "a commenté". */
  message: string;
  /** Who did it. Never oneself: you are not notified of your own actions. */
  author: string;
  /**
   * The item no longer exists: it has just been deleted. There is nothing
   * to open, the notification merely says so.
   */
  deleted: boolean;
  created_at: string;
}

/**
 * What travels on the event stream. The two messages are distinguished
 * by their shape rather than by a "type" field: the versions payload
 * existed before, and did not have to change.
 */
export type FeedMessage =
  | VersionPayload
  | { notification: Notification }
  | { m365: M365Change };

export const isNotification = (
  message: FeedMessage,
): message is { notification: Notification } => "notification" in message;

/**
 * What Graph says changed in what one of the person's widgets reads (server,
 * lib/m365-webhooks.ts): an e-mail arrived for a Mail widget, an appointment
 * moved for a Calendar one. The widgets reread without waiting.
 */
export type M365Change = "mail" | "calendar";

export const isM365Change = (message: FeedMessage): message is { m365: M365Change } =>
  "m365" in message;

/** The window event the client relays it as, which the widgets of that kind listen to. */
export const m365Event = (kind: M365Change): string => `milo:m365-${kind}`;
